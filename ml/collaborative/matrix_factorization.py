"""Matrix Factorization recommender using Truncated SVD — Phase 4B.

Decomposes the user-item interaction matrix into latent user and item factors
using scikit-learn's TruncatedSVD. Recommendations are generated by scoring
all items as the dot product of a user's latent vector with each item's latent
vector.

Design rationale (ADR-P4-02):
  - Dense matrix (99.6%) makes SVD well-conditioned.
  - scikit-learn's TruncatedSVD is fast and dependency-free beyond sklearn.
  - ALS (implicit library) is designed for sparse implicit feedback — not needed here.

Usage:
    from ml.collaborative.matrix_factorization import SVDRecommender

    rec = SVDRecommender(n_components=50)
    rec.fit(train_df)
    recs = rec.recommend(user_id=42, n=10, exclude_seen={100, 101})
"""

from __future__ import annotations

import time

import numpy as np
import polars as pl
from sklearn.decomposition import TruncatedSVD

from ml.baselines.base import BaseRecommender
from ml.baselines.popularity_recommender import PopularityRecommender
from ml.collaborative.interaction_matrix import build_interaction_matrix


class SVDRecommender(BaseRecommender):
    """Matrix Factorization recommender via Truncated SVD.

    Learns n_components latent dimensions for users and items.
    User embeddings: U × Σ  (shape n_users × n_components)
    Item embeddings: V^T    (shape n_components × n_items → transpose to n_items × n_components)

    Recommendation score: user_embedding @ item_embeddings.T

    Args:
        n_components:    Number of latent dimensions (singular values to keep).
        max_watch_ratio: Clip watch_ratio before building interaction matrix.
        random_state:    Random seed for TruncatedSVD (reproducibility).
        fallback:        Recommender for cold-start users.
        random_seed:     Passed to BaseRecommender.
    """

    def __init__(
        self,
        n_components: int = 50,
        max_watch_ratio: float = 5.0,
        random_state: int = 42,
        fallback: BaseRecommender | None = None,
        random_seed: int = 42,
    ) -> None:
        super().__init__(random_seed=random_seed)
        self._n_components = n_components
        self._max_watch_ratio = max_watch_ratio
        self._random_state = random_state
        self._fallback: BaseRecommender = fallback or PopularityRecommender(
            popularity_metric="weighted_score"
        )

        # Populated during fit()
        self._user_to_row: dict[int, int] = {}
        self._col_to_item: dict[int, int] = {}
        self._item_to_col: dict[int, int] = {}
        self._user_embeddings: np.ndarray | None = None   # (n_users, n_components)
        self._item_embeddings: np.ndarray | None = None   # (n_items, n_components)
        self._item_scores_cache: np.ndarray | None = None  # (n_users, n_items)
        self._fit_seconds: float = 0.0

    @property
    def name(self) -> str:
        return f"SVDRecommender(k={self._n_components})"

    def fit(self, train_df: pl.DataFrame) -> None:
        """Decompose the interaction matrix into user and item embeddings.

        Args:
            train_df: Training interactions (user_id, video_id, watch_ratio).
        """
        t0 = time.time()

        matrix, self._user_to_row, self._item_to_col, _, col_to_item = (
            build_interaction_matrix(train_df, max_watch_ratio=self._max_watch_ratio)
        )
        self._col_to_item = col_to_item

        n_components = min(self._n_components, matrix.shape[0] - 1, matrix.shape[1] - 1)

        svd = TruncatedSVD(n_components=n_components, random_state=self._random_state)
        # U × Σ: each user's projection in latent space
        user_latent = svd.fit_transform(matrix)  # (n_users, n_components)
        # V^T: item embeddings (singular vectors)
        item_latent = svd.components_.T  # (n_items, n_components)

        self._user_embeddings = user_latent.astype(np.float32)
        self._item_embeddings = item_latent.astype(np.float32)

        # Pre-compute all user × item scores: (n_users, n_items)
        self._item_scores_cache = (
            self._user_embeddings @ self._item_embeddings.T
        )  # (n_users, n_items)

        # Fit fallback
        self._fallback.fit(train_df)

        self._fit_seconds = time.time() - t0
        self._fitted = True

    def recommend(
        self,
        user_id: int,
        n: int,
        exclude_seen: set[int],
    ) -> list[int]:
        """Return top-N SVD recommendations.

        Args:
            user_id:      Target user.
            n:            Number of recommendations.
            exclude_seen: Items to exclude.

        Returns:
            Ranked list of up to n video_ids.
        """
        self._check_fitted()

        if user_id not in self._user_to_row:
            return self._fallback.recommend(user_id, n, exclude_seen)

        assert self._item_scores_cache is not None

        u_row = self._user_to_row[user_id]
        scores_row = self._item_scores_cache[u_row]  # (n_items,)

        sorted_col_indices = np.argsort(scores_row)[::-1]
        result = []
        for col_idx in sorted_col_indices:
            vid = self._col_to_item[int(col_idx)]
            if vid not in exclude_seen:
                result.append(vid)
                if len(result) >= n:
                    break

        # Fill remainder from fallback if needed
        if len(result) < n:
            fallback_recs = self._fallback.recommend(
                user_id, n - len(result), exclude_seen | set(result)
            )
            result.extend(fallback_recs)

        return result[:n]

    @property
    def fit_seconds(self) -> float:
        return self._fit_seconds
